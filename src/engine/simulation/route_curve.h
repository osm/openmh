#ifndef MH_ROUTE_CURVE_H
#define MH_ROUTE_CURVE_H

#include "engine/core/error.h"
#include "engine/navigation/route.h"

/*
 * Repeat-mode interpolation in raw route-frame units. Parsed, unmodified route
 * required. Preserve binary32 stores and extended arithmetic. These helpers do
 * not mutate a projection cache. All outputs remain unchanged on failure.
 */
enum mh_error_code	mh_route_curve_sample(const struct mh_route *route,
	double frame, float output[9], struct mh_error *error_out);

/*
 * Symmetric samples, increasing half-width by .5 until their separation reaches
 * .5 world units. Fails after 99 unsuccessful attempts.
 */
enum mh_error_code	mh_route_curve_direction(const struct mh_route *route,
	double frame, float output[3], struct mh_error *error_out);

/* Finish normal and plane generated by reset, independent of car pose. */
enum mh_error_code	mh_route_finish_plane(const struct mh_route *route,
	float output[4], struct mh_error *error_out);

#endif
