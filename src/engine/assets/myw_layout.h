#ifndef MH_ASSETS_MYW_LAYOUT_H
#define MH_ASSETS_MYW_LAYOUT_H

/* Private disk layout shared by the MYW reader and owned decoder. */
enum {
	HEADER_BYTES = 240,
	BLOCK_BYTES = 12,
	MODEL_BYTES = 228,
	CELL_BYTES = 24,
	LIGHT_BYTES = 196,
	LINK_BYTES = 8,
	HALO_BYTES = 120,
	POINT_LIGHT_TYPE = 1,
	HALO_TYPE = 2,
	FIXED_SLICE_COUNT = 4,
	SLICE_COUNT = 5
};

/* Serialized fields; unrelated runtime/scratch bytes stay opaque. */
enum {
	HEADER_FILE_SIZE = 0x04,
	HEADER_GRID_WIDTH = 0x08,
	HEADER_GRID_HEIGHT = 0x0c,
	HEADER_CELL_SIZE = 0x10,
	HEADER_GRID_MINIMUM = 0x20,
	HEADER_DIRECTIONAL_COLOR = 0x44,
	HEADER_DIRECTIONAL_INTENSITY = 0x48,
	HEADER_DIRECTIONAL_DIRECTION = 0x4c,
	HEADER_GRID_OFFSET = 0x58,
	HEADER_BLOCK_COUNT = 0x5c,
	HEADER_BLOCK_SIZE = 0x60,
	HEADER_BLOCK_OFFSET = 0x64
};

enum {
	MODEL_SPHERE = 0x70,
	MODEL_PRIMITIVE_COUNT = 0x86,
	MODEL_PRIMITIVE_OFFSET = 0x9c,
	CELL_LIGHT_HEAD = 0x08,
	CELL_HALO_COUNT = 0x10,
	CELL_HALO_OFFSET = 0x14,
	LIGHT_POSITION = 0x04,
	LIGHT_COLOR = 0x1c,
	LIGHT_INTENSITY = 0x28,
	LIGHT_RADIUS = 0x2c,
	LINK_NEXT = 0x04,
	HALO_RESOURCE = 0x04,
	HALO_ENDPOINTS = 0x08,
	HALO_COLOR = 0x30
};

#endif
