#ifndef MH_ASSETS_WAVE_LAYOUT_H
#define MH_ASSETS_WAVE_LAYOUT_H

/* RIFF chunk headers and the PCM fmt payload, in bytes. */
enum {
	MH_WAVE_FOURCC_BYTES = 4,
	MH_WAVE_CHUNK_SIZE = 4,
	MH_WAVE_CHUNK_HEADER_BYTES = 8,
	MH_WAVE_HEADER_BYTES = 12,
	MH_WAVE_FORMAT_BYTES = 16,
	MH_WAVE_PCM_FORMAT = 1,
	MH_WAVE_FORMAT_CHANNELS = 2,
	MH_WAVE_FORMAT_RATE = 4,
	MH_WAVE_FORMAT_BYTE_RATE = 8,
	MH_WAVE_FORMAT_ALIGN = 12,
	MH_WAVE_FORMAT_BITS = 14,
	MH_WAVE_PCM_FORMAT_OFFSET =
		MH_WAVE_HEADER_BYTES + MH_WAVE_CHUNK_HEADER_BYTES,
	MH_WAVE_PCM_DATA_CHUNK =
		MH_WAVE_PCM_FORMAT_OFFSET + MH_WAVE_FORMAT_BYTES,
	MH_WAVE_PCM_HEADER_BYTES =
		MH_WAVE_PCM_DATA_CHUNK + MH_WAVE_CHUNK_HEADER_BYTES
};

#endif
