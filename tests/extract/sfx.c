static int failures;

static void
check(int valid, const char *message)
{
	if (!valid) {
		fprintf(stderr, "%s\n", message);
		failures++;
	}
}

static void
reject(const unsigned char *bytes, size_t size, int packed)
{
	struct mh_archive *archive;

	archive = NULL;
	check(mh_unshield_sfx_open(bytes, size, packed, &archive, NULL) !=
				MH_ERROR_NONE &&
			archive == NULL,
		"reject malformed SFX without publishing output");
	mh_archive_close(archive);
}

static void
verify(const unsigned char *bytes, size_t size, int packed)
{
	struct mh_archive *archive;
	struct mh_file file;
	enum mh_error_code status;
	size_t i;

	archive = NULL;
	status = mh_unshield_sfx_open(bytes, size, packed, &archive, NULL);
	check(status == MH_ERROR_NONE, "open SFX record");

	if (status != MH_ERROR_NONE)
		return;

	check(mh_archive_count(archive) == 1 &&
			strcmp(mh_archive_entry(archive, 0)->path,
				"disk1/SETUP.INI") == 0,
		"decode original case and remove build-machine prefix");
	status = mh_archive_read(archive, 0, sizeof(expected), &file, NULL);
	check(status == MH_ERROR_NONE, "read SFX payload");

	if (status == MH_ERROR_NONE) {
		check(file.size == sizeof(expected) &&
				memcmp(file.data, expected, sizeof(expected)) ==
					0,
			"payload matches independent bytes");
		free(file.data);
	}

	mh_archive_close(archive);

	for (i = 0; i < size; i++)
		reject(bytes, i, packed);
}

int
main(void)
{
	unsigned char duplicate[sizeof(plain) * 2];
	unsigned char damaged[sizeof(compressed)];
	struct mh_archive *archive;
	struct mh_file file;
	enum mh_error_code status;

	verify(plain, sizeof(plain), 0);
	verify(compressed, sizeof(compressed), 1);
	reject(unsafe, sizeof(unsafe), 0);
	reject(plain, sizeof(plain), 1);
	memcpy(duplicate, plain, sizeof(plain));
	memcpy(duplicate + sizeof(plain), plain, sizeof(plain));
	reject(duplicate, sizeof(duplicate), 0);

	memcpy(damaged, compressed, sizeof(compressed));

	/* 12-byte record header + 24-byte name + local ZIP CRC offset 14. */
	damaged[12 + 24 + 14] ^= 1;
	archive = NULL;
	status = mh_unshield_sfx_open(
		damaged, sizeof(damaged), 1, &archive, NULL);
	check(status == MH_ERROR_NONE,
		"index compressed member before decoding");

	if (status == MH_ERROR_NONE) {
		file.data = NULL;
		check(mh_archive_read(archive, 0, sizeof(expected), &file,
			NULL) != MH_ERROR_NONE &&
				file.data == NULL,
			"reject corrupt ZIP payload without publishing bytes");
		mh_archive_close(archive);
	}

	return failures != 0;
}
